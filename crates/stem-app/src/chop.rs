//! Chop mode state: which stem and region are chopped, how, the resulting slices pre-rendered
//! for the pads, pad hits for the UI, and the per-session settings file (`chop.json` in the
//! session folder). Slicing itself lives in `stem_audio::chop`; drawing in `views/chop.rs`.

use std::path::{Path, PathBuf};
use std::sync::Arc;

use crossbeam_channel::Receiver;
use serde::{Deserialize, Serialize};
use stem_audio::AudioBuffer;
use stem_audio::analysis::BeatGrid;
use stem_audio::chop::{self, GridStep, OnsetCurve, Slice, TransientParams};
use stem_models::StemKind;

use crate::pads::PadVoices;

/// Pads per page (a 4×4 MPC grid).
pub const PADS: usize = 16;
/// Most slices kept (8 pages, A–H).
pub const MAX_SLICES: usize = PADS * 8;
/// Settings file inside the session folder.
const FILE: &str = "chop.json";
/// Shortest slice, seconds.
const MIN_SLICE: f64 = 0.02;
/// Zero-crossing search radius, seconds.
const ZERO_RADIUS: f64 = 0.0015;
/// Anti-click fades on rendered slices, seconds.
const FADE_IN: f64 = 0.0007;
const FADE_OUT: f64 = 0.004;

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, Default)]
pub enum ChopMode {
    #[default]
    Transients,
    Grid,
    Equal,
    Manual,
}

impl ChopMode {
    pub const ALL: [ChopMode; 4] = [
        ChopMode::Transients,
        ChopMode::Grid,
        ChopMode::Equal,
        ChopMode::Manual,
    ];
    pub fn label(self) -> &'static str {
        match self {
            ChopMode::Transients => "Transients",
            ChopMode::Grid => "Grid",
            ChopMode::Equal => "Equal",
            ChopMode::Manual => "Manual",
        }
    }
}

/// Grid chop resolution (serialisable twin of [`GridStep`]).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, Default)]
pub enum GridChoice {
    HalfBeat,
    #[default]
    Beat,
    TwoBeats,
    Bar,
    TwoBars,
    FourBars,
}

impl GridChoice {
    pub const ALL: [GridChoice; 6] = [
        GridChoice::HalfBeat,
        GridChoice::Beat,
        GridChoice::TwoBeats,
        GridChoice::Bar,
        GridChoice::TwoBars,
        GridChoice::FourBars,
    ];
    pub fn label(self) -> &'static str {
        match self {
            GridChoice::HalfBeat => "½ beat",
            GridChoice::Beat => "Beat",
            GridChoice::TwoBeats => "2 beats",
            GridChoice::Bar => "Bar",
            GridChoice::TwoBars => "2 bars",
            GridChoice::FourBars => "4 bars",
        }
    }
    pub fn step(self) -> GridStep {
        match self {
            GridChoice::HalfBeat => GridStep::HalfBeat,
            GridChoice::Beat => GridStep::Beat,
            GridChoice::TwoBeats => GridStep::TwoBeats,
            GridChoice::Bar => GridStep::Bar,
            GridChoice::TwoBars => GridStep::TwoBars,
            GridChoice::FourBars => GridStep::FourBars,
        }
    }
}

/// What gets saved per session.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(default)]
pub struct ChopSettings {
    /// Stem being chopped; `None` = pick drums (or the first stem).
    pub stem: Option<StemKind>,
    pub mode: ChopMode,
    /// Transient sensitivity, 0..=100.
    pub sensitivity: f32,
    /// Minimum gap between transients, ms.
    pub min_gap_ms: f32,
    pub grid: GridChoice,
    /// Equal mode: number of parts.
    pub parts: u32,
    /// Chopped range in seconds; `None` = the whole stem.
    pub region: Option<(f64, f64)>,
    /// Cut points in seconds (not counting the region start). Generated by the automatic
    /// modes; edited by hand in manual mode.
    pub markers: Vec<f64>,
    /// Mono: a new hit cuts the ones still ringing.
    pub choke: bool,
    /// Pad page (A = 0).
    pub page: usize,
    /// Also write a Decent Sampler preset next to the SFZ.
    pub dspreset: bool,
}

impl Default for ChopSettings {
    fn default() -> Self {
        Self {
            stem: None,
            mode: ChopMode::Transients,
            sensitivity: 55.0,
            min_gap_ms: 90.0,
            grid: GridChoice::Beat,
            parts: 16,
            region: None,
            markers: Vec::new(),
            choke: false,
            page: 0,
            dspreset: true,
        }
    }
}

/// A pad hit, for the flash.
#[derive(Debug, Clone, Copy, Default)]
pub struct Hit {
    pub at: f64,
    pub velocity: f32,
}

/// Result of a background chop export: number of slices and the folder.
pub type ExportResult = Result<(usize, PathBuf), String>;

/// Chop mode for one session.
pub struct ChopState {
    /// The results page shows the chop view instead of the stem cards.
    pub open: bool,
    pub settings: ChopSettings,
    /// What's on disk, to save only on change.
    saved: Option<ChopSettings>,
    /// Session track being chopped.
    pub track: usize,
    /// Slices of the current track, frames.
    pub slices: Vec<Slice>,
    /// Pre-rendered slices (fades applied), parallel to `slices`.
    pub pads: Vec<Arc<AudioBuffer>>,
    /// Mini waveform per slice: peak per column, 0..=1.
    pub minis: Vec<Vec<f32>>,
    pub hits: Vec<Hit>,
    /// Pads held down (mouse / keys), lit while held.
    pub held: Vec<usize>,
    /// Zoom window inside the region, seconds.
    pub view: Option<(f64, f64)>,
    /// Marker being dragged.
    pub dragging: Option<usize>,
    /// Slice under the pointer (waveform or pad), from the last frame.
    pub hover: Option<usize>,
    /// Regenerate markers from the mode (automatic modes) on the next update.
    regen: bool,
    /// Re-slice and re-render the pads on the next update.
    reslice: bool,
    curve: Option<((usize, usize, usize), OnsetCurve)>,
    voices: Option<PadVoices>,
    /// Running export.
    pub export_rx: Option<Receiver<ExportResult>>,
    /// When `chop.json` was last written (app time, seconds).
    last_save: f64,
}

impl ChopState {
    /// Settings saved for the session in `out_dir`, or defaults.
    pub fn load(out_dir: &Path) -> Self {
        let saved: Option<ChopSettings> = std::fs::read_to_string(out_dir.join(FILE))
            .ok()
            .and_then(|s| serde_json::from_str(&s).ok());
        Self {
            open: false,
            settings: saved.clone().unwrap_or_default(),
            saved,
            track: 0,
            slices: Vec::new(),
            pads: Vec::new(),
            minis: Vec::new(),
            hits: Vec::new(),
            held: Vec::new(),
            view: None,
            dragging: None,
            hover: None,
            // Saved markers are kept as they are; only fresh sessions chop from scratch.
            regen: false,
            reslice: true,
            curve: None,
            voices: None,
            export_rx: None,
            last_save: f64::NEG_INFINITY,
        }
        .with_regen_if_empty()
    }

    fn with_regen_if_empty(mut self) -> Self {
        if self.saved.is_none() {
            self.regen = true;
        }
        self
    }

    /// The chop view was just opened: a session chopped for the first time starts from the
    /// current selection, if there is one.
    pub fn opened(&mut self, selection: Option<(f64, f64)>) {
        if self.saved.is_none()
            && self.settings.region.is_none()
            && let Some(sel) = selection
        {
            self.settings.region = Some(sel);
            self.retarget();
        }
    }

    /// Settings changed in a way that moves the automatic markers.
    pub fn changed(&mut self) {
        if self.settings.mode != ChopMode::Manual {
            self.regen = true;
        }
        self.reslice = true;
    }

    /// Stem or region changed: forget the zoom and the onset cache.
    pub fn retarget(&mut self) {
        self.view = None;
        self.settings.page = 0;
        // Manual markers stay; ones outside the new region are dropped by the slicer.
        self.regen = self.settings.mode != ChopMode::Manual;
        self.reslice = true;
    }

    /// Track index for the chosen stem.
    pub fn resolve_track(&self, kinds: &[StemKind]) -> usize {
        let want = self.settings.stem.or_else(|| {
            kinds
                .iter()
                .copied()
                .find(|k| *k == StemKind::Drums)
                .or(kinds.first().copied())
        });
        want.and_then(|k| kinds.iter().position(|x| *x == k))
            .unwrap_or(0)
    }

    /// Region in seconds, clamped to the track.
    pub fn region(&self, duration: f64) -> (f64, f64) {
        match self.settings.region {
            Some((a, b)) if b - a > MIN_SLICE => (a.clamp(0.0, duration), b.clamp(0.0, duration)),
            _ => (0.0, duration),
        }
    }

    /// Bring markers, slices and pads up to date. Cheap when nothing changed.
    pub fn update(
        &mut self,
        kinds: &[StemKind],
        audio: &[AudioBuffer],
        grid: Option<&BeatGrid>,
        duration: f64,
    ) {
        let track = self.resolve_track(kinds);
        if track != self.track {
            self.track = track;
            self.regen = self.settings.mode != ChopMode::Manual;
            self.reslice = true;
        }
        let Some(buf) = audio.get(track) else {
            self.slices.clear();
            self.pads.clear();
            return;
        };
        let sr = buf.sample_rate.max(1) as f64;
        let (a, b) = self.region(duration.min(buf.duration_secs()));
        let (fa, fb) = ((a * sr) as usize, ((b * sr) as usize).min(buf.frames()));
        if self.regen {
            self.regen = false;
            self.reslice = true;
            if let Some(points) = self.generate(buf, grid, fa, fb) {
                self.settings.markers = points;
            }
        }
        if !self.reslice {
            return;
        }
        self.reslice = false;
        let radius = (ZERO_RADIUS * sr) as usize;
        let mut points: Vec<usize> = self
            .settings
            .markers
            .iter()
            .map(|t| chop::snap_to_zero(buf, (t * sr) as usize, radius))
            .collect();
        points.sort_unstable();
        let start = chop::snap_to_zero(buf, fa, radius).min(fb);
        let mut slices = chop::slices_from_points(&points, start, fb, (MIN_SLICE * sr) as usize);
        slices.truncate(MAX_SLICES);
        self.slices = slices;
        // While a marker is dragged only the slice edges move; pads render on release.
        if self.dragging.is_none() {
            self.render(buf);
        }
        let pages = self.pages();
        if self.settings.page >= pages {
            self.settings.page = pages.saturating_sub(1);
        }
    }

    /// Cut points (seconds) for the automatic modes; `None` in manual mode.
    fn generate(
        &mut self,
        buf: &AudioBuffer,
        grid: Option<&BeatGrid>,
        fa: usize,
        fb: usize,
    ) -> Option<Vec<f64>> {
        let sr = buf.sample_rate.max(1) as f64;
        let s = &self.settings;
        let frames: Vec<usize> = match s.mode {
            ChopMode::Manual => return None,
            ChopMode::Transients => {
                let key = (self.track, fa, fb);
                if self.curve.as_ref().is_none_or(|(k, _)| *k != key) {
                    self.curve = Some((key, OnsetCurve::compute(buf, fa, fb)));
                }
                let params = TransientParams {
                    sensitivity: s.sensitivity / 100.0,
                    min_gap_secs: s.min_gap_ms as f64 / 1000.0,
                };
                self.curve
                    .as_ref()
                    .map(|(_, c)| c.pick(buf.sample_rate, params))
                    .unwrap_or_default()
            }
            ChopMode::Grid => match grid {
                Some(g) => chop::grid_points(g, fa as f64 / sr, fb as f64 / sr, s.grid.step())
                    .into_iter()
                    .map(|t| (t * sr) as usize)
                    .collect(),
                None => chop::equal_points(fa, fb, s.parts as usize),
            },
            ChopMode::Equal => chop::equal_points(fa, fb, s.parts.max(1) as usize),
        };
        Some(
            frames
                .into_iter()
                .filter(|&f| f > fa && f < fb)
                .map(|f| f as f64 / sr)
                .collect(),
        )
    }

    fn render(&mut self, buf: &AudioBuffer) {
        let sr = buf.sample_rate.max(1) as f64;
        let (fi, fo) = ((FADE_IN * sr) as usize, (FADE_OUT * sr) as usize);
        self.pads = self
            .slices
            .iter()
            .map(|s| Arc::new(chop::render_slice(buf, *s, fi, fo)))
            .collect();
        self.minis = self.pads.iter().map(|p| mini_wave(p, 36)).collect();
        self.hits.resize(self.slices.len(), Hit::default());
    }

    pub fn pages(&self) -> usize {
        self.slices.len().div_ceil(PADS).max(1)
    }

    // ---- marker editing (switches to manual mode) ----------------------------------------

    fn make_manual(&mut self) {
        self.settings.mode = ChopMode::Manual;
        self.reslice = true;
    }

    /// Add a cut at `t` seconds; returns its marker index.
    pub fn add_marker(&mut self, t: f64) -> usize {
        self.make_manual();
        let m = &mut self.settings.markers;
        let i = m.partition_point(|x| *x < t);
        m.insert(i, t);
        i
    }

    pub fn remove_marker(&mut self, i: usize) {
        if i < self.settings.markers.len() {
            self.make_manual();
            self.settings.markers.remove(i);
        }
    }

    /// Move marker `i` to `t`, keeping the list sorted; returns its new index.
    pub fn move_marker(&mut self, i: usize, t: f64) -> usize {
        if i >= self.settings.markers.len() {
            return i;
        }
        self.make_manual();
        let m = &mut self.settings.markers;
        m.remove(i);
        let j = m.partition_point(|x| *x < t);
        m.insert(j, t);
        j
    }

    /// Finish a marker drag (renders the pads).
    pub fn end_drag(&mut self) {
        self.dragging = None;
        self.reslice = true;
    }

    // ---- pads ----------------------------------------------------------------------------

    /// Play slice `i` (`velocity` 0..=1) and flash its pad.
    pub fn trigger(
        &mut self,
        i: usize,
        velocity: f32,
        now: f64,
        player: &mut crate::player::Player,
    ) {
        let Some(buf) = self.pads.get(i).cloned() else {
            return;
        };
        if self.voices.is_none()
            && let Some(mixer) = player.mixer()
        {
            self.voices = Some(PadVoices::new(&mixer, buf.sample_rate));
        }
        if let Some(v) = &self.voices {
            // Velocity curve: soft hits are quieter but never silent.
            let gain = 0.25 + 0.75 * velocity.clamp(0.0, 1.0).powf(1.5);
            v.trigger(i, buf, gain, self.settings.choke);
        }
        if let Some(h) = self.hits.get_mut(i) {
            *h = Hit {
                at: now,
                velocity: velocity.clamp(0.0, 1.0),
            };
        }
    }

    pub fn stop_all(&mut self) {
        if let Some(v) = &self.voices {
            v.stop_all();
        }
        for h in &mut self.hits {
            h.at = f64::NEG_INFINITY;
        }
    }

    /// Something is still sounding or flashing (keep repainting).
    pub fn animating(&self, now: f64) -> bool {
        self.voices.as_ref().is_some_and(|v| v.active() > 0)
            || !self.held.is_empty()
            || self.export_rx.is_some()
            || self
                .hits
                .iter()
                .zip(&self.pads)
                .any(|(h, p)| now - h.at < (p.duration_secs() + 0.1).max(0.5))
    }

    // ---- persistence ---------------------------------------------------------------------

    /// Write `chop.json` when the settings changed (not mid-drag, at most twice a second).
    pub fn persist(&mut self, out_dir: &Path, now: f64) {
        if self.dragging.is_some()
            || now - self.last_save < 0.5
            || self.saved.as_ref() == Some(&self.settings)
        {
            return;
        }
        self.last_save = now;
        let Ok(json) = serde_json::to_string_pretty(&self.settings) else {
            return;
        };
        match std::fs::write(out_dir.join(FILE), json) {
            Ok(()) => self.saved = Some(self.settings.clone()),
            Err(e) => {
                tracing::warn!("couldn't save chop settings: {e}");
                // Don't retry every frame.
                self.saved = Some(self.settings.clone());
            }
        }
    }
}

/// Peak per column of a slice, scaled so the loudest column is 1.
pub fn mini_wave(buf: &AudioBuffer, cols: usize) -> Vec<f32> {
    let peaks = buf.peaks(cols);
    let v: Vec<f32> = peaks
        .iter()
        .map(|(lo, hi)| hi.abs().max(lo.abs()))
        .collect();
    let max = v.iter().copied().fold(0.0f32, f32::max).max(1e-6);
    // Square root: quiet tails stay visible next to the attack.
    v.into_iter().map(|x| (x / max).sqrt()).collect()
}

/// Pad label for slice `i` on its page: "A1" … "A16", "B1" …
pub fn pad_name(i: usize) -> String {
    let page = (b'A' + (i / PADS).min(25) as u8) as char;
    format!("{page}{}", i % PADS + 1)
}

