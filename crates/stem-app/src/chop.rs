#[cfg(test)]
mod tests {
    use super::*;

    fn clicks() -> Vec<AudioBuffer> {
        let sr = 44_100;
        let mut x = vec![0.0f32; sr * 4];
        for k in 0..8 {
            let s = k * sr / 2 + 1000;
            for j in 0..2000 {
                x[s + j] = (j as f32 * 0.3).sin() * (-(j as f32) / 400.0).exp();
            }
        }
        vec![AudioBuffer::new(sr as u32, vec![x])]
    }

    #[test]
    fn modes_and_manual_edits() {
        let audio = clicks();
        let kinds = [StemKind::Drums];
        let dir = std::env::temp_dir().join("stem-chop-test-none");
        let mut st = ChopState::load(&dir);
        st.update(&kinds, &audio, None, 4.0);
        // Eight clicks after a short lead-in: the lead-in is slice 1.
        assert_eq!(st.slices.len(), 9, "{:?}", st.settings.markers);
        assert_eq!(st.pads.len(), 9);
        assert!(st.slices.windows(2).all(|w| w[0].end == w[1].start));

        st.settings.mode = ChopMode::Equal;
        st.settings.parts = 4;
        st.changed();
        st.update(&kinds, &audio, None, 4.0);
        assert_eq!(st.slices.len(), 4);

        // Hand edits switch to manual and survive further updates.
        let i = st.add_marker(0.3);
        assert_eq!(st.settings.mode, ChopMode::Manual);
        st.update(&kinds, &audio, None, 4.0);
        assert_eq!(st.slices.len(), 5);
        let j = st.move_marker(i, 3.9);
        assert_eq!(j, st.settings.markers.len() - 1);
        st.remove_marker(j);
        st.changed();
        st.update(&kinds, &audio, None, 4.0);
        assert_eq!(st.slices.len(), 4);

        // A region limits the slices.
        st.settings.mode = ChopMode::Equal;
        st.settings.region = Some((1.0, 2.0));
        st.retarget();
        st.update(&kinds, &audio, None, 4.0);
        assert_eq!(st.slices.len(), 4);
        let sr = 44_100.0;
        assert!((st.slices[0].start as f64 / sr - 1.0).abs() < 0.002);
        assert!((st.slices[3].end as f64 / sr - 2.0).abs() < 0.002);
    }

    #[test]
    fn settings_roundtrip_and_names() {
        let dir = std::env::temp_dir().join(format!("stem-chop-test-{}", std::process::id()));
        std::fs::create_dir_all(&dir).unwrap();
        let mut st = ChopState::load(&dir);
        st.settings.parts = 7;
        st.settings.markers = vec![0.5, 1.5];
        st.persist(&dir, 0.0);
        let back = ChopState::load(&dir);
        assert_eq!(back.settings, st.settings);
        let _ = std::fs::remove_dir_all(&dir);
        assert_eq!(pad_name(0), "A1");
        assert_eq!(pad_name(17), "B2");
        let m = mini_wave(&clicks()[0], 10);
        assert_eq!(m.len(), 10);
        assert!((m.iter().copied().fold(0.0, f32::max) - 1.0).abs() < 1e-6);
    }
}
